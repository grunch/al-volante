// Validates every content catalog (structure + cross-references) and prints a coverage summary.
// Usage: node scripts/validate-content.ts   (Node ≥ 24 runs TypeScript natively by stripping types)
import { existsSync, readFileSync, readdirSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { activityKeyOf } from '../src/content/activityFiles.ts';
import { auditCoverage, computeCoverage } from '../src/content/coverage.ts';
import { figureFile, signFile } from '../src/content/figures.ts';
import { ACTIVITY_DIRECTORY, validateContent } from '../src/content/validate.ts';
import type { RawContent } from '../src/content/validate.ts';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const read = (path: string): unknown => JSON.parse(readFileSync(join(root, path), 'utf8'));

const raw: RawContent = {
  manifest: read('specs/fuentes/manifest.json'),
  pages: read('specs/catalog/pages.json'),
  units: read('specs/catalog/units.json'),
  signs: read('specs/catalog/signs.json'),
  issues: read('specs/catalog/issues.json'),
  rules: read('specs/catalog/rules.json'),
  route: read('specs/route/comuna13-a.json'),
  figures: read('specs/catalog/figures.json'),
  theoryExam: read('specs/catalog/theory-exam.json'),
  activities: Object.fromEntries(
    readdirSync(join(root, ACTIVITY_DIRECTORY))
      .filter((name) => name.endsWith('.json'))
      .map((name) => [activityKeyOf(name), read(`${ACTIVITY_DIRECTORY}/${name}`)]),
  ),
};

const result = validateContent(raw);
if (!result.ok) {
  console.error(`Content has ${result.errors.length} error(s):`);
  for (const error of result.errors) console.error(`- ${error}`);
  process.exit(1);
}

const { content, version } = result;
// The crops are generated by scripts/crop-figures.ts and shipped from public/; a missing one would break a page.
const missingImages = [
  ...content.figures.map((figure) => figureFile(figure.id)),
  ...content.signs.filter((sign) => sign.box).map((sign) => signFile(sign.id)),
].filter((file) => !existsSync(join(root, 'public', file)));
if (missingImages.length > 0) {
  console.error(`Missing images (run node scripts/crop-figures.ts):`);
  for (const file of missingImages) console.error(`- public/${file}`);
  process.exit(1);
}
console.log(
  `Content OK (version ${version}): ${content.pages.length} pages, ${content.units.length} units, ${content.signs.length} signs, ` +
    `${content.issues.length} issues, ${content.rules.rules.length} rules, ${content.route.legs.length} route legs, ` +
    `${content.figures.length} figures, ${content.signs.filter((sign) => sign.box).length} sign crops, ` +
    `${content.activities.length} activities.`,
);
for (const row of computeCoverage(content)) {
  console.log(
    `  ${row.source}/${row.section} [${row.category}]: ${row.units} units, ${row.unitsWithActivities} with activities, ` +
      `${row.consultationUnits} for consultation, ${row.reviewedUnits} reviewed`,
  );
}
const audit = auditCoverage(content);
console.log(
  `Coverage: ${audit.units.total - audit.units.untreated.length}/${audit.units.total} units treated ` +
    `(${audit.units.practiced} practised, ${audit.units.consultation} for consultation), ` +
    `${audit.signs.total - audit.signs.untreated.length}/${audit.signs.total} signs treated ` +
    `(${audit.signs.total - audit.signs.withoutCrop.length} cropped), ` +
    `${audit.unclassifiedPages.length} unclassified pages.`,
);
